import type { Metadata, Viewport } from "next";
import { headers } from "next/headers";
import type { ReactNode } from "react";
import { theme } from "../theme.ts";
import "./globals.css";

export const metadata: Metadata = {
  title: { default: theme.productName, template: `%s · ${theme.productName}` },
  description: "Document-processing agent platform",
};

export const viewport: Viewport = { width: "device-width", initialScale: 1 };

export default async function RootLayout({ children }: { children: ReactNode }) {
  // Every page is rendered per request, so Next.js can put the request's Content Security
  // Policy nonce (proxy.ts) on its scripts; a page built ahead of time would have none.
  await headers();
  return (
    <html lang="en-GB">
      <head>
        {/* The theme's colours as CSS variables (app/theme.css/route.ts). */}
        {/* eslint-disable-next-line @next/next/no-css-tags -- generated by a route, not a CSS file to import */}
        <link rel="stylesheet" href="/theme.css" />
      </head>
      <body>{children}</body>
    </html>
  );
}
